export const pick = <T,>(arr: T[], s: string, salt: string) => arr[hash(`${s}::${salt}`) % arr.length];
export const rotate = <T,>(arr: T[], s: string, salt: string) => { if (!arr.length) return arr; const k = hash(`${s}::${salt}`) % arr.length; return [...arr.slice(k), ...arr.slice(0, k)]; };

